export type CardRateMeta = {
  flightReturnPct: number;
  otherReturnPct: number;
  pointValueMinor: number; // Value of 1 point in minor currency units (e.g. 1 cent in EUR = 1 minor unit)
  monthlyCapMinor: number | null;
};

