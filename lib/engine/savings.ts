// Calculate months between search date (now) and flight departure date
export function calculateMonthsUntilFlight(departureDateStr?: string): number {
  if (!departureDateStr) return 0;
  try {
    const now = new Date();
    const flightDate = new Date(departureDateStr);
    const yearDiff = flightDate.getFullYear() - now.getFullYear();
    const monthDiff = flightDate.getMonth() - now.getMonth();
    const dayDiff = flightDate.getDate() - now.getDate();

    let totalMonths = yearDiff * 12 + monthDiff;
    if (dayDiff > 15) {
      totalMonths += 1; // Round up half month
    }
    // Min 0, Max 12 months forward projection
    return Math.max(0, Math.min(12, totalMonths));
  } catch {
    return 0;
  }
}

export function calculateCardSavings(
  offer: FlightOffer,
  userCards: UserCard[],
  trip?: TripInput
): SavingsResult {
  const normalPrice = offer.totalMinor; // Total price in minor units (e.g. €69.14 = 6914 cents)
  const currency = offer.currency || "EUR";

  if (!userCards || userCards.length === 0) {
    const fallbackStrategy: Strategy = {
      heldPointsOffsetMinor: 0,
      spendPointsOffsetMinor: 0,
      redeemOffsetMinor: 0,
      earnBackMinor: 0,
      hackedPriceMinor: normalPrice,
      savingsMinor: 0,
      savingsPct: 0,
    };
    return {
      normalPriceMinor: normalPrice,
      currency,
      best: fallbackStrategy,
      alternatives: [],
      projection: { pointsByDeparture: {}, monthlyPointsEarned: {}, monthsUntilDeparture: 0 },
      assumptions: ["No wallet cards configured. Standard cash fare applies."],
    };
  }

  // Calculate the months until flight departure
  const departureDate = trip?.legs?.[0]?.date;
  const monthsUntilDeparture = calculateMonthsUntilFlight(departureDate);

  // Compute monthly points generated by user spending habits per card
  const monthlyPointsEarned: Record<string, number> = {};
  const totalProjectedPoints: Record<string, number> = {};

  userCards.forEach((c) => {
    const rule = CARD_RULES[c.cardId] || { flightReturnPct: 1.0, otherReturnPct: 1.0, pointValueMinor: 1.0, monthlyCapMinor: null };
    let monthlyRewardsMinor = 0;

    Object.entries(c.monthlySpendMinor || {}).forEach(([cat, minor]) => {
      const spendMinor = Number(minor) || 0;
      const ratePct = cat === "flights" ? rule.flightReturnPct : rule.otherReturnPct;
      monthlyRewardsMinor += spendMinor * (ratePct / 100);
    });

    const ptsPerMonth = rule.pointValueMinor > 0 ? Math.round(monthlyRewardsMinor / rule.pointValueMinor) : 0;
    monthlyPointsEarned[c.cardId] = ptsPerMonth;

    // Total points available by booking time = current held points + (monthly points * months)
    const futureAccumulatedPoints = ptsPerMonth * monthsUntilDeparture;
    totalProjectedPoints[c.cardId] = (Number(c.pointsBalance) || 0) + futureAccumulatedPoints;
  });

  const strategies: Strategy[] = [];

  // Evaluate each card strategy:
  for (const redeemCard of userCards) {
    const redeemRule = CARD_RULES[redeemCard.cardId] || {
      flightReturnPct: 1.0,
      otherReturnPct: 1.0,
      pointValueMinor: 1.0,
      monthlyCapMinor: null,
    };

    // 1. Points currently held in wallet (strictly from pointsBalance)
    const heldPts = Number(redeemCard.pointsBalance) || 0;
    const heldPtsValueMinor = Math.round(heldPts * redeemRule.pointValueMinor);
    const heldPointsOffset = Math.min(heldPtsValueMinor, normalPrice);
    const cashAfterHeld = Math.max(0, normalPrice - heldPointsOffset);

    // 2. Projected points accumulated from monthly spend until departure
    const monthlyPts = monthlyPointsEarned[redeemCard.cardId] || 0;
    const futureSpendPts = monthlyPts * monthsUntilDeparture;
    const futureSpendPtsValueMinor = Math.round(futureSpendPts * redeemRule.pointValueMinor);
    const spendPointsOffset = Math.min(futureSpendPtsValueMinor, cashAfterHeld);

    // Total points offset
    const redeemOffset = heldPointsOffset + spendPointsOffset;
    const cashRemainingToPay = Math.max(0, normalPrice - redeemOffset);

    // Now test which card is best to PAY the remaining cash with
    for (const payCard of userCards) {
      const payRule = CARD_RULES[payCard.cardId] || {
        flightReturnPct: 1.0,
        otherReturnPct: 1.0,
        pointValueMinor: 1.0,
        monthlyCapMinor: null,
      };

      // Rewards earned on remaining cash: cashRemainingToPay * return rate
      const rawEarnBack = Math.round(cashRemainingToPay * (payRule.flightReturnPct / 100));
      const earnBack = payRule.monthlyCapMinor
        ? Math.min(rawEarnBack, payRule.monthlyCapMinor)
        : rawEarnBack;

      const hackedPrice = Math.max(0, normalPrice - redeemOffset - earnBack);
      const savings = normalPrice - hackedPrice;
      const savingsPct = normalPrice > 0 ? Math.round((savings / normalPrice) * 100) : 0;

      strategies.push({
        redeemCardId: redeemOffset > 0 ? redeemCard.cardId : undefined,
        payCardId: payCard.cardId,
        heldPointsOffsetMinor: heldPointsOffset,
        spendPointsOffsetMinor: spendPointsOffset,
        redeemOffsetMinor: redeemOffset,
        earnBackMinor: earnBack,
        hackedPriceMinor: hackedPrice,
        savingsMinor: savings,
        savingsPct,
      });
    }
  }

  // Also evaluate pure payment with zero redemption
  for (const payCard of userCards) {
    const payRule = CARD_RULES[payCard.cardId] || {
      flightReturnPct: 1.0,
      otherReturnPct: 1.0,
      pointValueMinor: 1.0,
      monthlyCapMinor: null,
    };
    const rawEarnBack = Math.round(normalPrice * (payRule.flightReturnPct / 100));
    const earnBack = payRule.monthlyCapMinor
      ? Math.min(rawEarnBack, payRule.monthlyCapMinor)
      : rawEarnBack;
    const hackedPrice = Math.max(0, normalPrice - earnBack);
    const savings = normalPrice - hackedPrice;
    const savingsPct = normalPrice > 0 ? Math.round((savings / normalPrice) * 100) : 0;

    strategies.push({
      redeemCardId: undefined,
      payCardId: payCard.cardId,
      heldPointsOffsetMinor: 0,
      spendPointsOffsetMinor: 0,
      redeemOffsetMinor: 0,
      earnBackMinor: earnBack,
      hackedPriceMinor: hackedPrice,
      savingsMinor: savings,
      savingsPct,
    });
  }

  // Sort descending by highest savings
  strategies.sort((a, b) => b.savingsMinor - a.savingsMinor);

  // Filter unique strategies
  const uniqueStrategies: Strategy[] = [];
  const seenKeys = new Set<string>();
  for (const strat of strategies) {
    const key = `${strat.redeemCardId || "none"}-${strat.payCardId}`;
    if (!seenKeys.has(key)) {
      seenKeys.add(key);
      uniqueStrategies.push(strat);
    }
  }

  const best = uniqueStrategies[0] || strategies[0];
  const alternatives = uniqueStrategies.slice(1, 3);

  const bestCardMeta = CARDS_CATALOG.find((c) => c.id === best.payCardId);
  const timeDesc = monthsUntilDeparture > 0 ? `${monthsUntilDeparture} months accumulated spend` : "immediate balance";

  return {
    normalPriceMinor: normalPrice,
    currency,
    best,
    alternatives,
    projection: {
      pointsByDeparture: totalProjectedPoints,
      monthlyPointsEarned,
      monthsUntilDeparture,
    },
    assumptions: [
      `Optimal card for this flight: ${bestCardMeta?.name || best.payCardId}.`,
      `Includes ${timeDesc} based on flight date (${departureDate || "immediate"}).`,
      "Point valuations based on standard travel card redemption metrics in €.",
    ],
    ratesVerifiedAt: "2026-10-27",
  };
}
